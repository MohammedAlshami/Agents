"""
Argumentative Writing Style Sub-Prompt
Persuasive, evidence-based argument writing style.
"""

ARGUMENTATIVE_WRITING_PROMPT = """
**ARGUMENTATIVE WRITING STYLE:**

1. **Clear Position:**
   - State your position or thesis clearly and explicitly
   - Take a definitive stance on the issue
   - Avoid being wishy-washy or neutral
   - Make your argument's main point evident from the beginning

2. **Strong Evidence:**
   - Support your position with compelling evidence
   - Use facts, statistics, research findings, expert opinions
   - Include relevant examples and case studies
   - Cite credible sources to strengthen credibility

3. **Logical Reasoning:**
   - Build logical arguments with clear reasoning
   - Use deductive or inductive reasoning appropriately
   - Connect evidence to conclusions logically
   - Avoid logical fallacies (ad hominem, strawman, false dilemma, etc.)

4. **Counterarguments:**
   - Acknowledge opposing viewpoints fairly
   - Address counterarguments directly and respectfully
   - Refute opposing arguments with evidence and reasoning
   - Show why your position is stronger despite alternatives

5. **Persuasive Techniques:**
   - Use rhetorical devices effectively (analogy, parallel structure)
   - Appeal to logic (logos), emotion (pathos), and credibility (ethos)
   - Use strong, confident language
   - Create urgency or importance when appropriate

6. **Structure:**
   - Start with a clear introduction that establishes the issue and your position
   - Build arguments progressively with supporting evidence
   - Address counterarguments systematically
   - End with a strong conclusion that reinforces your position

7. **Tone and Language:**
   - Use confident, assertive language
   - Avoid hedging excessively ("might," "maybe," "possibly" used too much)
   - Maintain respect for opposing views
   - Use strong, active verbs

8. **Call to Action:**
   - Clearly state what action or change you're advocating
   - Explain why this action is important
   - Make recommendations explicit
   - Leave readers with a clear sense of what should happen next
"""

