DESCRIPTIVE_WRITING_PROMPT = """
**DESCRIPTIVE WRITING STYLE:**

1. **Vivid and Detailed:**
   - Use specific, concrete details rather than abstract generalizations
   - Appeal to multiple senses when relevant (sight, sound, touch, etc.)
   - Include specific examples and instances
   - Use precise adjectives and adverbs

2. **Sensory Language:**
   - Incorporate sensory details to create vivid imagery
   - Use descriptive language that helps readers visualize
   - Employ figurative language appropriately (similes, metaphors)
   - Focus on specific, observable details

3. **Organizational Patterns:**
   - Organize descriptions spatially (top to bottom, left to right, etc.)
   - Use chronological order when describing processes or sequences
   - Organize by importance (most to least important or vice versa)
   - Use logical groupings (by category, function, or characteristic)

4. **Clarity and Precision:**
   - Choose words that convey exact meaning
   - Avoid vague or generic descriptions
   - Use concrete nouns and specific verbs
   - Provide specific measurements, quantities, or dimensions when relevant

5. **Objective vs. Subjective:**
   - Use objective description for factual information
   - Use subjective description when appropriate (impressions, perceptions)
   - Clearly distinguish between observation and interpretation
   - Maintain appropriate tone for the context

6. **Techniques:**
   - Use concrete examples and illustrations
   - Include comparisons to familiar concepts
   - Break down complex subjects into manageable parts
   - Show rather than just tell

7. **Focus and Scope:**
   - Maintain clear focus on what is being described
   - Include relevant context and background
   - Provide sufficient detail without overwhelming
   - Highlight the most important or distinctive features
"""

