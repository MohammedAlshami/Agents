COMPARATIVE_WRITING_PROMPT = """
**COMPARATIVE WRITING STYLE:**

1. **Clear Comparison Framework:**
   - Establish clear criteria for comparison
   - Identify specific aspects to compare
   - Use consistent evaluation standards
   - Define the scope of comparison clearly

2. **Structured Organization:**
   - Option 1: Point-by-point comparison (alternating between subjects)
   - Option 2: Subject-by-subject comparison (complete coverage of each subject)
   - Use parallel structure when comparing similar aspects
   - Maintain balance in coverage of each subject

3. **Objective Comparison:**
   - Present information fairly for all subjects
   - Avoid bias toward one subject over another
   - Acknowledge both strengths and weaknesses
   - Use neutral, descriptive language

4. **Detailed Analysis:**
   - Provide specific details and examples for each comparison point
   - Highlight similarities and differences clearly
   - Explain the significance of differences
   - Use evidence to support comparative statements

5. **Transitional Language:**
   - Use comparison/contrast transitions: "similarly," "likewise," "in contrast," "however," "on the other hand"
   - Signal comparisons clearly: "compared to," "in comparison with," "relative to"
   - Indicate similarities: "both," "equally," "similarly"
   - Indicate differences: "unlike," "whereas," "while," "differ from"

6. **Conclusion and Synthesis:**
   - Synthesize comparison points into coherent conclusions
   - Identify which aspects are more significant
   - Provide overall evaluation when appropriate
   - Highlight key insights from the comparison

7. **Balance and Fairness:**
   - Give equal attention to all subjects being compared
   - Avoid superficial comparisons
   - Address complexity and nuance
   - Recognize when direct comparison may not be appropriate
"""

