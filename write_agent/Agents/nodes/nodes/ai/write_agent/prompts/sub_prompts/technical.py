TECHNICAL_WRITING_PROMPT = """
**TECHNICAL WRITING STYLE:**

1. **Clarity and Precision:**
   - Use clear, concise language
   - Define technical terms clearly on first use
   - Avoid ambiguity and vague expressions
   - Prefer active voice for procedures and actions

2. **Structure and Organization:**
   - Use headings and subheadings for clarity
   - Organize information logically and hierarchically
   - Use numbered lists for procedures
   - Use bullet points for related items

3. **Objective and Direct:**
   - Write in an objective, neutral tone
   - Focus on facts and information, not opinions
   - Use imperative mood for instructions ("Install the software," "Configure the settings")
   - Avoid emotional language

4. **Technical Details:**
   - Include necessary technical specifications
   - Provide examples and use cases where helpful
   - Use diagrams, tables, or code examples when appropriate (describe them in text)
   - Explain complex concepts step-by-step

5. **Audience Awareness:**
   - Write for the target technical audience
   - Assume appropriate level of technical knowledge
   - Explain unfamiliar concepts clearly
   - Use industry-standard terminology

6. **Formatting Conventions:**
   - Use consistent formatting throughout
   - Highlight important information appropriately
   - Use code formatting for technical terms when needed
   - Maintain clear visual hierarchy
"""

