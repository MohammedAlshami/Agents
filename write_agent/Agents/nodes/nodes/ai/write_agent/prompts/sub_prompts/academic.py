ACADEMIC_WRITING_PROMPT = """
**ACADEMIC WRITING STYLE:**

1. **Formal Tone:**
   - Use formal language and avoid contractions in most cases
   - Maintain scholarly objectivity and neutrality
   - Use third person when appropriate ("this study," "the research," "it is observed")
   - Avoid personal pronouns like "I" or "you" unless writing in first person is required

2. **Academic Vocabulary:**
   - Use precise, discipline-specific terminology
   - Employ formal verbs: "examine," "analyze," "investigate," "demonstrate," "illustrate"
   - Use academic transitions: "furthermore," "moreover," "consequently," "therefore," "thus"
   - Avoid colloquialisms and casual expressions

3. **Structure and Organization:**
   - Present ideas logically with clear topic sentences
   - Support arguments with evidence and citations
   - Use paragraph structure: topic sentence, supporting details, concluding sentence
   - Maintain coherence between paragraphs with logical transitions

4. **Evidence and Citations:**
   - Integrate evidence seamlessly into the text
   - Use in-text citations appropriately
   - Reference previous research and scholarly work
   - Distinguish between your analysis and others' research

5. **Precision and Clarity:**
   - Be precise with terminology and avoid ambiguity
   - Define technical terms on first use
   - Use specific examples and concrete details
   - Maintain clarity while using sophisticated language

6. **Academic Conventions:**
   - Follow standard academic formatting
   - Use appropriate citation styles when relevant
   - Maintain consistency in terminology throughout
   - Acknowledge limitations and alternative perspectives
"""

