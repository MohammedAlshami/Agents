"""
Analytical Writing Style Sub-Prompt
Analysis-focused, data-driven writing style.
"""

ANALYTICAL_WRITING_PROMPT = """
**ANALYTICAL WRITING STYLE:**

1. **Data-Driven Approach:**
   - Base arguments on evidence and data
   - Present quantitative and qualitative findings
   - Use statistics, trends, and patterns to support analysis
   - Distinguish between correlation and causation

2. **Critical Analysis:**
   - Examine multiple perspectives on the topic
   - Identify strengths and weaknesses in arguments
   - Evaluate evidence objectively
   - Question assumptions and explore underlying factors

3. **Logical Structure:**
   - Present analysis in a logical sequence
   - Use clear thesis statements and supporting evidence
   - Build arguments systematically
   - Connect findings to broader implications

4. **Objectivity:**
   - Maintain neutral, objective tone
   - Present data without personal bias
   - Acknowledge limitations in data or analysis
   - Distinguish between facts and interpretations

5. **Analysis Techniques:**
   - Break down complex topics into components
   - Compare and contrast different aspects
   - Identify patterns and trends
   - Explore cause-and-effect relationships
   - Evaluate significance and implications

6. **Evidence Integration:**
   - Support every claim with evidence
   - Cite sources appropriately
   - Use examples, case studies, or data points
   - Explain how evidence supports your analysis

7. **Conclusion-Oriented:**
   - Lead to clear conclusions based on analysis
   - Synthesize findings into coherent insights
   - Identify actionable implications
   - Suggest areas for further investigation
"""

